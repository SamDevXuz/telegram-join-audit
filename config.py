"""Пороги детектора.

Здесь нет секретов: движок анализа не обращается к Telegram API,
он работает с уже выгруженным списком заявок.

Важно: все константы подобраны на одном реальном наборе данных
(965 заявок, узбекоязычный канал). На другом канале их почти наверняка
придётся трогать. Это не универсальные значения.
"""

from zoneinfo import ZoneInfo


# Файл базы. Схема создаётся сама при первом analyzer.init().
DB_FILE = "requests.db"

# Часовой пояс для отчётов. На саму детекцию не влияет —
# внутри всё считается в UTC.
TIMEZONE = ZoneInfo("Asia/Tashkent")


# ---------------------------------------------------------------- Признак 1
# Однородность внутри всплеска.

# Минута считается «горячей», если в ней не меньше стольких заявок...
BURST_MIN_ABS = 8

# ...или во столько раз больше медианного потока. Порог адаптивный:
# что такое «много» для канала, решает сам канал.
BURST_FACTOR = 4

# Соседние горячие минуты с разрывом не больше этого склеиваются
# в одну сессию. Просадка на 20 секунд не повод рвать волну надвое.
BURST_GAP_MINUTES = 5

# Сессия помечается, если доля аккаунтов с аватаркой или с username
# выше органического фона канала на столько пунктов.
# Фон берётся из заявок, не попавших ни в одну сессию.
UNIFORMITY_GAP = 0.25


# ---------------------------------------------------------------- Признак 2
# Следы генератора в username.

# Семейство с общим корнем (например "userpn") считается подозрительным
# начиная с этого размера. Ниже 8 в выборку начинают проваливаться
# настоящие имена вроде @azizbek1224.
FAMILY_MIN = 8


# ---------------------------------------------------------------- Признак 3
# Даты первой аватарки. Требует предварительной глубокой проверки
# профилей (photos.getUserPhotos) — см. README.

# День считается «днём партии», если на него приходится не меньше
# BATCH_SHARE проверенных аккаунтов и не меньше BATCH_MIN_ABS штук.
BATCH_MIN_ABS = 10
BATCH_SHARE = 0.08

# Белый список: аккаунт с таким числом фотографий исключается
# из подозрений. Профиль, который копился годами, фермой не бывает.
HUMAN_PHOTOS = 5


# ---------------------------------------------------------------- Признак 4
# Кластеры соседних user ID. На выдержанных аккаунтах не работает —
# ловит только свежесозданные партии.

ID_GAP = 50_000
CLUSTER_MIN = 3


# ---------------------------------------------------------------- Прочее

# Порог индивидуального скора (0-100). Скор считается и показывается,
# но решение принимается по групповым признакам, а не по нему.
SUSPECT_THRESHOLD = 50

# Срок жизни одноразового кода доступа к панели доказательств.
GUEST_CODE_HOURS = 48
